# --------------------------------------------------------------------------- --market-exit
#: Per-strategy expected (rule ids, gene count) with --market-exit exit,stop,tp and both
#: profiles. S1-S5/S7 have a terminal catch-all floor stop that itself adjusts the stop-loss, so
#: the STOP rule is omitted (7 genes); S6 has no catch-all at all, so all four rules attach
#: (9 genes). Measured directly against the built strategies, not asserted from a formula, since
#: the omission depends on each strategy's own exit shape.
_EXPECTED_MARKET_EXIT_GENES = {
    "S1": 7, "S2": 7, "S3": 7, "S4": 7, "S5": 7, "S6": 9, "S7": 7,
}


@pytest.mark.parametrize("kind", EQUITY)
def test_market_exit_appends_after_the_existing_exits_and_passes_the_action_guard(kind):
    from ba2_common.core.market_condition_rules import assert_market_rule_actions

    plain = mod._build_strategy(kind, f"me-plain-{kind}", "FMPRating")   # defaults: no market exit

    mod._MARKET_CONDITION_PROFILES = BOTH_PROFILES
    mod._MARKET_CONDITION_MODE = mod._MARKET_CONDITION_MODE_SEARCHED
    mod._MARKET_EXIT_KINDS_SELECTED = ("exit", "stop", "tp")
    gated = mod._build_strategy(kind, f"me-gated-{kind}", "FMPRating")

    plain_ids = [r["id"] for r in plain.exit_rules]
    gated_ids = [r["id"] for r in gated.exit_rules]
    mkt_ids = [i for i in gated_ids if "-mkt-" in i]
    assert mkt_ids, kind
    # every ORIGINAL exit rule is still present, in its original relative order
    assert [i for i in gated_ids if i not in mkt_ids] == plain_ids, kind
    # market rules appended after every original exit that precedes them
    first_mkt = gated_ids.index(mkt_ids[0])
    assert set(gated_ids[:first_mkt]) <= set(plain_ids), kind

    assert_market_rule_actions(gated.exit_rules, f"{kind} exit rules")  # no exception = pass

    # Every market-exit gene's id (rule enable, leaf value, action value) is built from one of
    # the market rule ids, and no OTHER gene in these strategies ever contains "-mkt-" -- so this
    # is an exact, not a heuristic, count.
    all_genes = collect_param_space(gated)
    mkt_genes = sorted(g for g in all_genes if "-mkt-" in g)
    assert len(mkt_genes) == _EXPECTED_MARKET_EXIT_GENES[kind], (kind, mkt_genes)


