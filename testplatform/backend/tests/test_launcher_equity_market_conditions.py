def _market_ids(node) -> list:
    out: list = []

    def walk(n):
        if isinstance(n, list):
            for x in n:
                walk(x)
            return
        if not isinstance(n, dict):
            return
        cid = n.get("id")
        if isinstance(cid, str) and "-market-" in cid:
            out.append(cid)
        for v in n.values():
            walk(v)

    walk(node)
    return out


